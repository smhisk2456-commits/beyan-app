  final String surahNameEn;
  final String surahNameAr;
  final String verseReference;
  final String arabicText;
  final String textTr;
  final String textEn;
  final String textAr;

  const ShortVerseNotification({
    required this.surahNameTr,
    required this.surahNameEn,
    required this.surahNameAr,
    required this.verseReference,
    required this.arabicText,
    required this.textTr,
    required this.textEn,
    required this.textAr,
  });

  /// Seçili dile göre kısa ve vurucu meal metnini döner
  String localizedText(String langCode) {
    if (langCode == 'ar' || langCode == 'ur') return textAr;
    if (langCode == 'id') {
      return kIndonesianShortVerses[verseReference] ?? textEn;
    }
    if (langCode == 'en' || langCode == 'fr' || langCode == 'de' || langCode == 'ru') {
      return textEn;
    }
    return textTr;
  }

  /// Seçili dile göre sûre ve âyet referansını döner (örn: Ash-Sharh 94:5-6)
  String localizedReference(String langCode) {
    final parts = verseReference.split(' ');
    final nums = parts.length > 1 ? parts.sublist(1).join(' ') : '';
    if (langCode == 'ar' || langCode == 'ur') {
      final cleanSurah = surahNameAr.replaceAll('سورة ', '');
      return nums.isNotEmpty ? '$cleanSurah $nums' : surahNameAr;
    }
    if (langCode != 'tr') {
      final cleanSurah = surahNameEn.replaceAll('Surah ', '');
      return nums.isNotEmpty ? '$cleanSurah $nums' : surahNameEn;
    }
    return verseReference;
  }

  /// Seçili dile göre bildirim başlığını döner
  String localizedTitle(String langCode, {bool isEvening = false}) {
    final ref = localizedReference(langCode);
    if (isEvening) {
      if (langCode == 'en') return 'Evening Reflection 🌙 $ref';
      if (langCode == 'ar') return 'تأمل المساء 🌙 $ref';
      if (langCode == 'id') return 'Renungan Malam 🌙 $ref';
      if (langCode == 'fr') return 'Méditation du Soir 🌙 $ref';
      if (langCode == 'ur') return 'شام کی فکر 🌙 $ref';
      if (langCode == 'de') return 'Abend-Besinnung 🌙 $ref';
      if (langCode == 'ru') return 'Вечернее размышление 🌙 $ref';
      return 'Akşam Tefekkürü 🌙 $ref';
    }
    if (langCode == 'en') return 'Verse of the Day 📖 $ref';
    if (langCode == 'ar') return 'آية اليوم 📖 $ref';
    if (langCode == 'id') return 'Ayat Hari Ini 📖 $ref';
    if (langCode == 'fr') return 'Verset du Jour 📖 $ref';
    if (langCode == 'ur') return 'آج کی آیت 📖 $ref';
    if (langCode == 'de') return 'Vers des Tages 📖 $ref';
    if (langCode == 'ru') return 'Аят Дня 📖 $ref';
    return 'Günün Âyeti 📖 $ref';
  }

  static int _rotationCounter = 0;

  /// Test veya anlık gönderimlerde her tıklamada sırayla ve KESİNLİKLE FARKLI bir ayet seçer.
  static Future<ShortVerseNotification> getNextRotatingVerse() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      int lastIndex = prefs.getInt('beyan_last_verse_notif_idx') ?? 0;
      final nextIndex = (lastIndex + 1) % pool.length;
      await prefs.setInt('beyan_last_verse_notif_idx', nextIndex);
      return pool[nextIndex];
    } catch (_) {
      _rotationCounter = (_rotationCounter + 1) % pool.length;
      return pool[_rotationCounter];
    }
  }

  /// Belirli bir indeksteki kısa ayeti döner (zamanlamalar için)
  static ShortVerseNotification getByIndex(int index) {
    return pool[index.abs() % pool.length];
  }

  /// Önümüzdeki n gün veya saat için ASLA TEKRAR ETMEYEN eşsiz bir ayet listesi üretir.
  /// Son 60 gönderilmiş ayet geçmişini SharedPreferences'ta saklayarak mükerrerliği %100 önler.
  static Future<List<ShortVerseNotification>> getNonRepeatingBatch(int count) async {
    try {
      final prefs = await SharedPreferences.getInstance();
      List<String> rawHistory = prefs.getStringList('beyan_verse_history_indices') ?? [];
      List<int> history = rawHistory.map((s) => int.tryParse(s) ?? 0).toList();

      List<ShortVerseNotification> result = [];
      List<int> newlyPicked = [];

      // Havuz içinde geçmişte OLMAYAN indeksleri bul
      List<int> available = [];
      for (int i = 0; i < pool.length; i++) {
        if (!history.contains(i)) {
          available.add(i);
        }
      }

      // Eğer kalan ayet sayısı istenen sayıdan azsa geçmişi sıfırla/döndür
      if (available.length < count) {
        history.clear();
        available = List.generate(pool.length, (i) => i);
      }

      // Deterministik ama düzenli sırada ilerle
      int cursor = prefs.getInt('beyan_batch_cursor') ?? 0;
      for (int step = 0; step < count; step++) {
        final pickIndex = available[(cursor + step) % available.length];
        result.add(pool[pickIndex]);
        newlyPicked.add(pickIndex);
      }

      // Geçmişe ekle ve son 60 kayıtta sınırla
      history.addAll(newlyPicked);
      if (history.length > 60) {
        history = history.sublist(history.length - 60);
      }

      await prefs.setStringList('beyan_verse_history_indices', history.map((e) => e.toString()).toList());
      await prefs.setInt('beyan_batch_cursor', (cursor + count) % pool.length);

      return result;
    } catch (_) {
      // Fallback
      return List.generate(count, (i) => pool[(i * 3) % pool.length]);
    }
  }

